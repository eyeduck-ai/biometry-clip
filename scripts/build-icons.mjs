import {deflateSync} from 'node:zlib';
import {mkdir,writeFile} from 'node:fs/promises';

// One vector construction drives both the editable SVG and Chrome's PNG sizes.
// Six shutter blades form an iris; the two detached corner tips suggest transfer.
const background='#292c2c',foreground='#f3f1ec',radius=37,aperture=16.5;
const point=(r,degrees)=>{const a=degrees*Math.PI/180;return [64+r*Math.cos(a),64+r*Math.sin(a)];};
const rounded=point=>point.map(value=>+value.toFixed(3));
const pair=point=>rounded(point).join(' ');
const blades=Array.from({length:6},(_,index)=>{
  const angle=-90+index*60,start=angle+2,end=angle+58;
  const outer=Array.from({length:25},(_,step)=>point(radius,start+(end-start)*step/24));
  const inner=[point(aperture,angle+88),point(aperture,angle+32)];
  return {points:[...outer,...inner],path:`M${pair(outer[0])} A${radius} ${radius} 0 0 1 ${pair(outer.at(-1))} L${pair(inner[0])} L${pair(inner[1])} Z`};
});
const tips=[[[86,23],[106,20],[104,40]],[[42,105],[22,108],[24,88]]];
const polygons=[...blades.map(blade=>blade.points),...tips];
const mark=blades.map(blade=>`<path d="${blade.path}"/>`).join('')+tips.map(points=>`<polygon points="${points.map(pair).join(' ')}"/>`).join('');
const svg=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" role="img" aria-label="Biometry-Clip"><rect width="128" height="128" rx="27" fill="${background}"/><g fill="${foreground}">${mark}</g></svg>\n`;

const crc=buffer=>{let n=-1;for(const x of buffer){n^=x;for(let i=0;i<8;i++)n=(n>>>1)^((n&1)?0xedb88320:0);}return(n^-1)>>>0;};
function chunk(name,data){const type=Buffer.from(name),length=Buffer.alloc(4),sum=Buffer.alloc(4);length.writeUInt32BE(data.length);sum.writeUInt32BE(crc(Buffer.concat([type,data])));return Buffer.concat([length,type,data,sum]);}
function insidePolygon(x,y,points){
  let inside=false;
  for(let i=0,j=points.length-1;i<points.length;j=i++){
    const [xi,yi]=points[i],[xj,yj]=points[j];
    if((yi>y)!==(yj>y)&&x<(xj-xi)*(y-yi)/(yj-yi)+xi)inside=!inside;
  }
  return inside;
}
const insideBackground=(x,y)=>Math.hypot(Math.max(Math.abs(x-64)-37,0),Math.max(Math.abs(y-64)-37,0))<=27;
const rgb=hex=>[1,3,5].map(start=>parseInt(hex.slice(start,start+2),16));
const dark=rgb(background),light=rgb(foreground),samples=8;
function png(size){
  const raw=Buffer.alloc((size*4+1)*size),scale=128/size;
  for(let y=0;y<size;y++)for(let x=0;x<size;x++){
    const sum=[0,0,0];let covered=0;
    for(let sy=0;sy<samples;sy++)for(let sx=0;sx<samples;sx++){
      const px=(x+(sx+.5)/samples)*scale,py=(y+(sy+.5)/samples)*scale;
      if(!insideBackground(px,py))continue;
      covered++;const color=polygons.some(points=>insidePolygon(px,py,points))?light:dark;
      for(let channel=0;channel<3;channel++)sum[channel]+=color[channel];
    }
    const offset=y*(size*4+1)+1+x*4;
    raw.set([...sum.map(value=>covered?Math.round(value/covered):0),Math.round(255*covered/(samples*samples))],offset);
  }
  const head=Buffer.alloc(13);head.writeUInt32BE(size);head.writeUInt32BE(size,4);head[8]=8;head[9]=6;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',head),chunk('IDAT',deflateSync(raw)),chunk('IEND',Buffer.alloc(0))]);
}
await mkdir('public/icons',{recursive:true});
await writeFile('public/icons/biometry-graphite.svg',svg);
await writeFile('src/brand-icon.js','// Generated by scripts/build-icons.mjs from the same geometry as the toolbar icon.\nexport const BRAND_GLYPH = '+JSON.stringify('<g transform="scale(.15625)" fill="currentColor" stroke="none">'+mark+'</g>')+';\n');
for(const size of [16,48,128])await writeFile(`public/icons/${size}.png`,png(size));
